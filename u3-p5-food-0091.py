import pandas as pd 
import matplotlib.pyplot as plt
# ian gutierrez NC 0091
# 1. leer el archivo CSV comida pais india
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEIDOS DESDE CSV 0091---")
print(df_food_india)
print("\n--- mostrar nombre comida + ingredientes 0091---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- tiempo de cocinado mostrar 10 registros con head 0091---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- Grafica comida (x) tiempo cocinado (y) 0091---")
print("\n--- Grafica comida (x) texto a 30 grados 0091---")
nombre_y_hora.plot.bar(x='name',y='cook_time', rot=30)
plt.title('comida tipica de india ian 0091')
plt.xlabel('nombre platillo')
plt.ylabel('tiempo de cocinado')
plt.show()
plt.title(' gráfica de varias columnas ian 0091')
nombre_y_hora = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_hora.plot.bar(x='name', rot=30)
plt.title('grafica de 2 columnas ian 0091')
plt.xlabel('nombre platillo')
plt.ylabel('tiempo de cocinado prep y comida')
plt.show()
print("\n--- gráficas de barras apiladas una tras otra verticalmente 0091---")
nombre_y_hora.plot.bar(x='name', stacked=True)
plt.title('grafica apiladas ian 0091')
plt.xlabel('nombre platillo')
plt.ylabel('tiempo de cocinado prep y comida')
plt.show()
